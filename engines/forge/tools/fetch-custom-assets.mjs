// Download only the new operator and merge its entries without dropping other assets.
import { readFile, writeFile, mkdir, rename } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { buildPlan } from './assets/plan.mjs';
import { indexAudio } from './assets/audio.mjs';
import { Downloader } from './assets/downloader.mjs';
import { collectLeaves, downloadLeaves, resolveTemplate, contentHash } from './assets/manifest.mjs';
import { processModels } from './assets/spine.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const ids = ['char_4217_makoto', 'char_1015_aglna2', 'char_4182_oblvns', 'char_4138_narant'];
const research = JSON.parse(await readFile(join(root, 'docs/research/07-assets.json'), 'utf8'));
const pinned = JSON.parse(await readFile(join(root, 'tools/custom/operators-assets.json'), 'utf8'));
const operators = Object.fromEntries(ids.flatMap(id => {
  const entry = research.operators?.[id] ?? pinned[id];
  return entry ? [[id, entry]] : [];
}));
const missing = ids.filter(id => !operators[id]);
if (missing.length) throw new Error(`Missing pinned custom asset metadata: ${missing.join(', ')}`);
const plan = buildPlan({ assets07: { operators }, ops03: {}, enemies05: {}, maps05: {}, audio: indexAudio({}), modelsData: {} });
const template = { chars: plan.template.chars, skills: plan.template.skills, skillsById: plan.template.skillsById };
const models = new Map([...plan.models].filter(([key]) => ids.some(id => key.startsWith(`op:${id}:`))));
const assetRoot = join(root, 'public/assets');
const dl = new Downloader({ root: assetRoot, ledgerPath: join(root, '.cache/assets-ledger.json'), concurrency: 8, log: console.log });
await dl.loadLedger();
const errors = await downloadLeaves(collectLeaves(template), dl, assetRoot);
const spine = await processModels(models, { root: assetRoot, dl, cachePath: join(root, '.cache/spine-info.json'), download: true, log: console.log });
const resolved = resolveTemplate(template, { root: assetRoot, spine: spine.entries });
if (errors.length || resolved.misses.length) throw new Error(`Missing custom operator assets: ${[...errors, ...resolved.misses].join(', ')}`);
const path = join(root, 'data/assets.json');
const previous = JSON.parse(await readFile(path, 'utf8'));
for (const key of Object.keys(resolved.value)) previous[key] = { ...previous[key], ...resolved.value[key] };
const { version, hash, generator, stats, ...body } = previous;
previous.hash = contentHash(body);
previous.stats.chars = Object.keys(previous.chars).length;
await mkdir(assetRoot, { recursive: true });
await writeFile(path + '.tmp', JSON.stringify(previous));
await rename(path + '.tmp', path);
console.log(`Custom operator assets ready; ${models.size} models, existing manifest entries preserved.`);
